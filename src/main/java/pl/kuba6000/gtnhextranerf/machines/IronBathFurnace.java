/** Furnace registrations, construction recipes and informational material balances. */
public final class IronBathFurnace implements RecipeModule {

    public static final ResourceLocation FROZEN_BATH_TEXTURE = new ResourceLocation(
        "gregtech",
        "textures/blocks/fluids/fluid.molten.autogenerated.png");
    private static final int CONTROLLER_ID = 32410;
    private static final ItemList[] OUTPUTS = { ItemList.Hatch_Output_LV, ItemList.Hatch_Output_MV,
        ItemList.Hatch_Output_HV, ItemList.Hatch_Output_EV, ItemList.Hatch_Output_IV, ItemList.Hatch_Output_LuV,
        ItemList.Hatch_Output_ZPM, ItemList.Hatch_Output_UV, ItemList.Hatch_Output_UHV, ItemList.Hatch_Output_UEV,
        ItemList.Hatch_Output_UIV, ItemList.Hatch_Output_UMV, ItemList.Hatch_Output_UXV, ItemList.Hatch_Output_MAX };

    public static final int CASING_TEXTURE_INDEX = (127 << 7) | 123;
    public static ITexture CASING_TEXTURE;
    public static final RecipeMap<RecipeMapBackend> RECIPES = RecipeMapBuilder.of("gtnhextranerf.recipe.iron_bath")
        .maxIO(3, 0, 0, 2)
        .minInputs(3, 0)
        .disableRegisterNEI()
        .build();

    private static IronBathCasings casings;
    private static ItemStack controller;
    private static ItemStack measurement;
    private static final ItemStack[] TAPS = new ItemStack[OUTPUTS.length];

    public static void registerBlocks() {
        if (casings != null) throw new IllegalStateException("Iron bath casings are already registered");
        casings = new IronBathCasings();
        casings.register();
        CASING_TEXTURE = TextureFactory.of(casings, 0);
    }

    public static void registerMachines() {
        GTUtility.addTexturePage((byte) 127);
        if (Textures.BlockIcons.getCasingTextureForId(CASING_TEXTURE_INDEX) != null)
            throw new IllegalStateException("Iron bath casing texture ID is occupied");
        Textures.BlockIcons.setCasingTextureForId(CASING_TEXTURE_INDEX, CASING_TEXTURE);
        for (int offset = 0; offset <= OUTPUTS.length + 1; offset++) {
            if (GregTechAPI.METATILEENTITIES[CONTROLLER_ID + offset] != null)
                throw new IllegalStateException("Iron bath machine ID is occupied: " + (CONTROLLER_ID + offset));
        }
        controller = new MTEIronBathFurnace(CONTROLLER_ID, "multimachine.gtnhextranerf.iron_bath", "Electric Iron Bath")
            .getStackForm(1);
        for (int tier = 1; tier <= TAPS.length; tier++) {
            TAPS[tier - 1] = new MTEIronBathTap(
                CONTROLLER_ID + tier,
                "hatch.gtnhextranerf.iron_bath_tap." + tier,
                GTValues.VN[tier] + " Iron Bath Tap",
                tier).getStackForm(1);
        }
        measurement = new MTEIronBathMeasurement(
            CONTROLLER_ID + OUTPUTS.length + 1,
            "hatch.gtnhextranerf.iron_bath_measurement",
            "Bath Measurement Hatch").getStackForm(1);
    }

    public static ItemStack measurementHatch() {
        if (measurement == null) throw new IllegalStateException("Iron bath measurement hatch has not been registered");
        return measurement.copy();
    }

    public static ItemStack controller() {
        if (controller == null) throw new IllegalStateException("Iron bath controller has not been registered");
        return controller.copy();
    }

    public static ItemStack tap(int tier) {
        if (tier < 1 || tier > TAPS.length) throw new IllegalArgumentException("Invalid iron bath tap tier: " + tier);
        if (TAPS[tier - 1] == null) throw new IllegalStateException("Iron bath taps have not been registered");
        return TAPS[tier - 1].copy();
    }

    public static ItemStack casing(int metadata, int amount) {
        if (metadata < 0 || metadata > 1) throw new IllegalArgumentException("Invalid iron bath casing metadata");
        return new ItemStack(casingBlock(), amount, metadata);
    }

    public static Block casingBlock() {
        if (casings == null) throw new IllegalStateException("Iron bath casings have not been registered");
        return casings;
    }

    public static Materials material(IronProduct product) {
        return switch (product) {
            case IRON -> Materials.Iron;
            case WROUGHT_IRON -> IronBathMaterials.wroughtIron();
            case STEEL -> Materials.Steel;
            case CAST_IRON -> Materials.CastIron;
            case PIG_IRON -> Materials.PigIron;
            case OVERCARBURIZED_IRON -> IronBathMaterials.overcarburizedIron();
            case SLAG -> IronBathMaterials.slag();
        };
    }

    public static IronProduct product(Materials material) {
        if (material == Materials.IronMagnetic) return IronProduct.IRON;
        if (material == Materials.SteelMagnetic) return IronProduct.STEEL;
        for (IronProduct product : IronProduct.values())
            if (product != IronProduct.SLAG && material(product) == material) return product;
        return null;
    }

    public static IronBath.Fuel fuel(ItemStack stack) {
        if (stack.getItem() == Items.coal)
            return stack.getItemDamage() == 1 ? IronBath.Fuel.CHARCOAL : IronBath.Fuel.COAL;
        ItemData data = GTOreDictUnificator.getItemData(stack);
        if (data != null && data.mPrefix == OrePrefixes.dust) {
            if (data.mMaterial.mMaterial == Materials.Coal) return IronBath.Fuel.COAL;
            if (data.mMaterial.mMaterial == Materials.Charcoal) return IronBath.Fuel.CHARCOAL;
        }
        for (int id : OreDictionary.getOreIDs(stack)) {
            String name = OreDictionary.getOreName(id);
            if ("fuelCactusCoke".equals(name) || "itemCokeCactus".equals(name)) return IronBath.Fuel.CACTUS_COKE;
            if ("fuelSugarCoke".equals(name) || "itemCokeSugar".equals(name)) return IronBath.Fuel.SUGAR_COKE;
        }
        for (int id : OreDictionary.getOreIDs(stack)) {
            if ("fuelCoke".equals(OreDictionary.getOreName(id))) return IronBath.Fuel.COKE;
        }
        return null;
    }

    @Override
    public void register(RecipeRegistry registry) {
        registry.register(AuditScope.ADD_IRON_BATH_RECIPES, IronBathFurnace::recipes);
    }

    private static void recipes(RecipeContext recipes) {
        assemble(
            recipes,
            casing(0, 1),
            1,
            nativeItem(ItemList.Casing_Firebricks),
            part(OrePrefixes.foil, Materials.Steel, 4));
        assemble(
            recipes,
            casing(1, 1),
            1,
            casing(0, 1),
            part(OrePrefixes.plate, IronBathMaterials.wroughtIron(), 2),
            NHItemList.MicaInsulatorFoil.get(4));
        assemble(
            recipes,
            controller(),
            1,
            nativeItem(ItemList.Hull_LV),
            part(OrePrefixes.plate, Materials.Steel, 4),
            part(OrePrefixes.cableGt01, Materials.Copper, 2),
            circuit(1, 2));
        assemble(
            recipes,
            measurementHatch(),
            6,
            nativeItem(ItemList.Hull_LuV),
            GTUtility.copyAmount(2, nativeItem(ItemList.Sensor_LuV)),
            circuit(6, 2));
        for (int tier = 1; tier <= TAPS.length; tier++) {
            assemble(
                recipes,
                tap(tier),
                tier,
                nativeItem(OUTPUTS[tier - 1]),
                part(OrePrefixes.plate, Materials.Steel, 2),
                part(OrePrefixes.ring, Materials.Steel, 1),
                circuit(tier, 1));
        }
        preserveCastIron(recipes, OrePrefixes.ingot, ItemList.Shape_Mold_Ingot, 144, 32, 7);
        preserveCastIron(recipes, OrePrefixes.nugget, ItemList.Shape_Mold_Nugget, 16, 16, 4);
        preserveCastIron(recipes, OrePrefixes.block, ItemList.Shape_Mold_Block, 1296, 288, 7);
        cast(
            recipes,
            IronBathMaterials.slag(),
            GTUtility.getIntegratedCircuit(1),
            part(OrePrefixes.dust, IronBathMaterials.slag(), 1));
        for (Materials material : new Materials[] { IronBathMaterials.wroughtIron(),
            IronBathMaterials.overcarburizedIron() }) {
            ItemStack ingot = part(OrePrefixes.ingot, material, 1);
            ItemStack dust = part(OrePrefixes.dust, material, 1);
            recipes.machine(RecipeMaps.maceratorRecipes)
                .requireExactlyOne(
                    RecipeMatch.builder()
                        .itemInputs(ingot)
                        .itemOutputs(dust)
                        .build());
            recipes.machine(RecipeMaps.fluidSolidifierRecipes)
                .requireExactlyOne(
                    RecipeMatch.builder()
                        .itemOutputs(part(OrePrefixes.ingot, material, 1))
                        .fluidInputs(material.getMolten(144))
                        .build());
        }
        balance(recipes, new ItemStack(Items.coal, 1, 0), IronBath.Fuel.COAL);
        balance(recipes, RecipeItems.requireModItem(Mods.Railcraft, "fuel.coke", 1, 0), IronBath.Fuel.COKE);
        balance(recipes, new ItemStack(Items.coal, 1, 1), IronBath.Fuel.CHARCOAL);
        balance(recipes, GregtechItemList.CactusCoke.get(1), IronBath.Fuel.CACTUS_COKE);
        balance(recipes, GregtechItemList.SugarCoke.get(1), IronBath.Fuel.SUGAR_COKE);
    }

    private static void assemble(RecipeContext recipes, ItemStack output, int tier, Object... inputs) {
        for (int slot = 0; slot < inputs.length; slot++) {
            Object input = inputs[slot];
            boolean valid = input instanceof ItemStack stack && stack.getItem() != null && stack.stackSize > 0;
            if (input instanceof Object[]ore && ore.length == 2 && ore[0] != null && ore[1] instanceof Number amount) {
                valid = amount.intValue() > 0 && GTOreDictUnificator.getOres(ore[0])
                    .stream()
                    .anyMatch(stack -> stack != null && stack.getItem() != null);
            }
            if (!valid) throw new RecipeValidationException(
                "Missing iron bath " + GTValues.VN[tier]
                    + " assembler ingredient in slot "
                    + slot
                    + " for "
                    + output.getDisplayName());
        }
        recipes.machine(RecipeMaps.assemblerRecipes)
            .addOne(
                GTRecipeBuilder.builder()
                    .itemInputs(inputs)
                    .itemOutputs(output)
                    .duration(200)
                    .eut(GTValues.VP[tier]),
                RecipeMatch.builder()
                    .itemOutputs(output)
                    .build());
    }

    private static ItemStack nativeItem(ItemList item) {
        ItemStack stack = item.get(1);
        if (stack == null || stack.getItem() == null)
            throw new RecipeValidationException("Missing native iron bath construction item: " + item.name());
        return stack;
    }

    private static Object[] circuit(int tier, int amount) {
        Materials[] tiers = { Materials.LV, Materials.MV, Materials.HV, Materials.EV, Materials.IV, Materials.LuV,
            Materials.ZPM, Materials.UV, Materials.UHV, Materials.UEV, Materials.UIV, Materials.UMV, Materials.UXV,
            Materials.MAX };
        Materials material = tiers[tier - 1];
        if (material == null || material == Materials._NULL)
            throw new RecipeValidationException("Missing native circuit material for iron bath tier " + tier);
        Object ore = OrePrefixes.circuit.get(material);
        if (GTOreDictUnificator.getOres(ore)
            .isEmpty()) throw new RecipeValidationException("Missing iron bath circuit ingredient: " + ore);
        return new Object[] { ore, amount };
    }

    private static void preserveCastIron(RecipeContext recipes, OrePrefixes form, ItemList mold, int fluidAmount,
        int duration, int eut) {
        ItemStack iron = part(form, Materials.Iron, 1);
        recipes.machine(RecipeMaps.fluidSolidifierRecipes)
            .modifyOne(
                RecipeMatch.builder()
                    .itemInputs(mold.get(0))
                    .fluidInputs(Materials.CastIron.getMolten(fluidAmount))
                    .itemOutputs(iron)
                    .fluidOutputs()
                    .duration(duration)
                    .eut(eut)
                    .build(),
                RecipeChange.builder()
                    .replaceItemOutput(iron, part(form, Materials.CastIron, 1))
                    .build());
    }

    private static void cast(RecipeContext recipes, Materials material, ItemStack shape, ItemStack output) {
        recipes.machine(RecipeMaps.fluidSolidifierRecipes)
            .addOne(
                GTRecipeBuilder.builder()
                    .itemInputs(shape)
                    .fluidInputs(material.getMolten(144))
                    .itemOutputs(output)
                    .duration(32)
                    .eut(8),
                RecipeMatch.builder()
                    .itemInputs(shape)
                    .fluidInputs(material.getMolten(144))
                    .itemOutputs(output)
                    .build());
    }

    private static void balance(RecipeContext recipes, ItemStack carbon, IronBath.Fuel fuel) {
        IronProduct.BatchBalance batch = IronProduct.STEEL.balance(fuel);
        ItemStack[] inputs = { part(OrePrefixes.ingot, Materials.Iron, batch.ironItems()),
            GTUtility.copyAmountUnsafe(batch.fuelItems(), carbon),
            part(OrePrefixes.dust, Materials.Calcite, (int) Math.ceil(batch.calciteItems())) };
        recipes.machine(RECIPES)
            .addOne(
                GTRecipeBuilder.builder()
                    .itemInputsUnsafe(inputs)
                    .fluidOutputs(
                        Materials.Steel.getMolten(batch.metalMb()),
                        IronBathMaterials.slag()
                            .getMolten(batch.slagMb()))
                    .duration(1)
                    .eut(0)
                    .fake(),
                RecipeMatch.builder()
                    .itemInputs(inputs)
                    .fluidOutputs(
                        Materials.Steel.getMolten(batch.metalMb()),
                        IronBathMaterials.slag()
                            .getMolten(batch.slagMb()))
                    .build());
    }

    private static ItemStack part(OrePrefixes prefix, Materials material, int amount) {
        ItemStack stack = GTOreDictUnificator.get(prefix, material, 1);
        if (stack == null)
            throw new IllegalStateException("Missing iron bath construction material: " + prefix + material);
        return GTUtility.copyAmountUnsafe(amount, stack);
    }

    public static void verify() {
        AuditManager.run(AuditScope.VERIFY_IRON_BATH, audit -> {
            IronBathMaterials.verify();
            if (!(GregTechAPI.METATILEENTITIES[CONTROLLER_ID] instanceof MTEIronBathFurnace)
                || !(GregTechAPI.METATILEENTITIES[CONTROLLER_ID + OUTPUTS.length + 1] instanceof MTEIronBathMeasurement)
                || Textures.BlockIcons.getCasingTextureForId(CASING_TEXTURE_INDEX) != CASING_TEXTURE
                || RECIPES.getAllRecipes()
                    .size() != 5)
                throw new IllegalStateException("Iron bath registry or reference balances are incomplete");
            for (int tier = 1; tier <= TAPS.length; tier++) {
                if (!(GregTechAPI.METATILEENTITIES[CONTROLLER_ID + tier] instanceof MTEIronBathTap))
                    throw new IllegalStateException("Iron bath tap is missing: " + tier);
            }
            audit.success();
        });
    }
}
